"""위기 표현 안내 (서비스 PRD 17장).

답변에서 심각한 심리적 위기 표현이 감지되면, 판단이나 평가 없이
전문 도움 정보를 안내한다. 원칙:

- 감지 결과를 저장하거나 기록에 라벨링하지 않는다 (감정 분석 금지 원칙과 일관).
- AI 가 위로/상담하지 않는다 — 안내 문구 한 번만, 응답 필드로 전달.
- 오탐이 사용자 경험을 해치므로 패턴은 보수적으로 유지한다
  ("끝내고 싶다" 같은 일상 표현과 겹치는 패턴은 넣지 않는다).
"""
import re

# 명백한 위기 표현만 (보수적 — 정밀도 우선)
_CRISIS_PATTERNS = [
    re.compile(p) for p in (
        r"죽고\s*싶",
        r"자살",
        r"자해",
        r"살고\s*싶지\s*않",
        r"살기\s*싫",
        r"사라지고\s*싶",
        r"목숨을?\s*끊",
    )
]

# 판단·평가 없이 정보만 전달한다. 문구 수정 시 톤앤매너(서비스 PRD 13장) 유지.
SAFETY_NOTICE = (
    "당신의 이야기를 소중히 담았어요. 혼자 감당하기 어려운 마음이 이어진다면, "
    "자살예방 상담전화 109 또는 정신건강 위기상담 1577-0199 에서 "
    "언제든 전문가와 이야기를 나눌 수 있어요."
)


def crisis_notice(text: str) -> str | None:
    """위기 표현이 감지되면 안내 문구, 아니면 None."""
    if any(p.search(text) for p in _CRISIS_PATTERNS):
        return SAFETY_NOTICE
    return None
