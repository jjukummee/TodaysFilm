def build_entries_block(entries: list[dict]) -> str:
    """리포트용 기록 목록 → 프롬프트 텍스트."""
    lines = []
    for e in entries:
        kw = ", ".join(e.get("keywords", []))
        lines.append(f"- {e['date']} | {e.get('film_title') or ''} | {e.get('representative_sentence') or ''} | 키워드: {kw}")
    return "\n".join(lines)


def build_qa_block(history) -> str:
    """QAItem 리스트 → 프롬프트용 텍스트 블록."""
    lines = []
    for i, item in enumerate(history, 1):
        lines.append(f"질문 {i}: {item.question}")
        lines.append(f"답변 {i}: {'(건너뜀)' if item.skipped else item.answer}")
    return "\n".join(lines)
